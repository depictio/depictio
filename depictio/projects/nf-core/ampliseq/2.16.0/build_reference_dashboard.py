# Sections the reference dataset cannot fill. The ampliseq reference run is a
# normal 16S run, so `sintax_rel_abundance` is pruned by the template's
# `if_var_absent: SKIP_QIIME` rule and every SINTAX tile disappears at import.
# The *sections* do not: the import prunes components, never section specs, and
# a section's text header has no data_collection_tag so it is always kept. The
# shipped seed therefore carried an empty "SINTAX scope" filter card and a
# "SINTAX classifier" section holding nothing but its own explanatory text.
# base.yaml keeps both, because a real --skip_qiime run needs them.
SINTAX_SECTIONS = ("SINTAX scope", "SINTAX classifier")


def strip_sections(dashboard: dict[str, Any], names: tuple[str, ...]) -> None:
    """Drop the named sections and every component assigned to them."""
    dropped = 0
    for tab in [dashboard["main_dashboard"], *dashboard.get("tabs", [])]:
        for key in ("filter_sections", "grid_sections"):
            if key in tab:
                tab[key] = [s for s in tab[key] if s.get("name") not in names]
        before = len(tab.get("components", []))
        tab["components"] = [c for c in tab.get("components", []) if c.get("section") not in names]
        dropped += before - len(tab["components"])
    print(f"  stripped {names}: {dropped} components removed")


def set_upset_set_colors(dashboard: dict[str, Any], colors: dict[str, str]) -> None:
    """Give every upset_plot an explicit set -> colour map.

    Without it `color_intersections_by: set` falls through to plotly-upset's
    `self.color` default for every bar, which is #333333 — the whole plot
    renders black. base.yaml cannot carry this map because its set names are
    {GROUP_COL} values, unknown until a run is ingested; the reference run's
    are the four habitats.
    """
    for tab in [dashboard["main_dashboard"], *dashboard.get("tabs", [])]:
        for comp in tab.get("components", []):
            cfg = comp.get("config") or {}
            if cfg.get("viz_kind") == "upset_plot":
                cfg["set_colors"] = dict(colors)
                # base.yaml leaves this on `degree` because a generic template
                # cannot name its sets. Here they are the four habitats, so the
                # UpSet can carry the same colours as every other habitat tile.
                cfg["color_intersections_by"] = "set"
                print(f"  set_colors on {comp.get('index', comp.get('tag'))}")


def annotate_heatmap_columns(
    dashboard: dict[str, Any], group_col: str, id_col: str, colors: dict[str, str]
) -> None:
    """Give every clustered heatmap a habitat strip above its columns.

    Both heatmaps have samples for columns, and until now nothing on either said
    which habitat a column came from: the clustering visibly groups the samples,
    and the reader had no way to check that the groups it found are the habitats.
    The row annotation cannot answer that, because `row_annotation_cols` reads
    columns of the heatmap's own DC and habitat lives in the metadata.

    base.yaml cannot carry this: `col_annotations` is a literal
    ``{column_label: category}`` map, so it names this run's samples. That is
    exactly the kind of run-specific value the demo layer exists for.
    """
    metadata = Path(__file__).parent / "input" / "Metadata_full.tsv"
    with metadata.open(encoding="utf-8") as handle:
        rows = list(csv.DictReader(handle, delimiter="\t"))
    by_sample = {r[id_col]: r[group_col] for r in rows if r.get(id_col) and r.get(group_col)}
    if not by_sample:
        raise SystemExit(f"no {id_col}/{group_col} pairs in {metadata}")

    for tab in [dashboard["main_dashboard"], *dashboard.get("tabs", [])]:
        for comp in tab.get("components", []):
            cfg = comp.get("config") or {}
            if cfg.get("viz_kind") != "complex_heatmap":
                continue
            cfg["col_annotations"] = {group_col: dict(by_sample)}
            # Same four hexes as every other habitat tile. Without the override
            # the strip picks its own categorical palette and the dashboard
            # shows two different colours for Riverwater on the same screen.
            cfg["col_annotation_colors"] = {group_col: dict(colors)}
            print(f"  {group_col} column strip on {comp.get('index', comp.get('tag'))}")


CHARS_PER_ROW = 300
GRID_COLS = 8


def fit_text_tiles(dashboard: dict[str, Any]) -> None:
    """Give every text tile enough rows for its body, then close the gap.

    The viewer autofits text tiles at render (TextRenderer measures its prose
    and DashboardGrid turns that into rows), so this is only the stored estimate
    that decides the first paint. It is deliberately rough: a tighter number
    here buys nothing, and too generous a one leaves the tile half empty for the
    instant before the measurement lands.

    Re-packs the section afterwards so a changed height does not leave the tile
    overlapping its neighbour in the stored layout.

    Section-scoped because DashboardGrid mounts one ResponsiveGridLayout per
    section (DashboardGrid.tsx:566), so y is section-relative.
    """
    bumped = 0
    for tab in [dashboard["main_dashboard"], *dashboard.get("tabs", [])]:
        left = {s.get("name") for s in (tab.get("filter_sections") or [])}
        buckets: dict[Any, list] = {}
        touched: set = set()
        for comp in tab.get("components", []):
            if comp.get("placement") == "left" or comp.get("section") in left:
                continue
            layout = comp.get("layout")
            if not isinstance(layout, dict):
                continue
            if comp.get("component_type") == "text":
                need = max(1, math.ceil(len(comp.get("body") or "") / CHARS_PER_ROW))
                if need != layout["h"]:
                    layout["h"] = need
                    touched.add(comp.get("section"))
                    bumped += 1
            buckets.setdefault(comp.get("section"), []).append(layout)
        for name, items in buckets.items():
            if name not in touched:
                continue
            heights = [0] * GRID_COLS
            for item in sorted(items, key=lambda d: (d["y"], d["x"])):
                span = range(item["x"], min(item["x"] + item["w"], GRID_COLS))
                item["y"] = max((heights[c] for c in span), default=0)
                for col in span:
                    heights[col] = item["y"] + item["h"]
    print(f"  fit text tiles: {bumped} raised")


def build() -> dict[str, Any]:
    variables = load_reference_vars()
    dashboard = substitute(yaml.safe_load(BASE_YAML.read_text()), variables)
    dashboard = copy.deepcopy(dashboard)

    group_col = variables["GROUP_COL"]
    group_display = variables["GROUP_COL_DISPLAY"]
    id_col = variables["METADATA_ID_COL"]

    strip_sections(dashboard, SINTAX_SECTIONS)
    set_upset_set_colors(dashboard, HABITAT_COLORS)
    annotate_heatmap_columns(dashboard, group_col, id_col, HABITAT_COLORS)

    main = dashboard["main_dashboard"]
    main["title"] = "nf-core/ampliseq"
    main["subtitle"] = "Ammer catchment reference dataset — QC, diversity, campaign and environment"
    main_tab_layer(main, group_col, id_col)

    next_order = max(t.get("tab_order", 0) for t in dashboard["tabs"]) + 1
    dashboard["tabs"].append(sampling_campaign_tab(group_col, group_display, id_col, next_order))
    dashboard["tabs"].append(environment_tab(group_col, group_display, id_col, next_order + 1))

    # Last, so it also covers the two tabs appended just above.
    fit_text_tiles(dashboard)
    return dashboard


def main() -> int:
    dashboard = build()
    body = yaml.safe_dump(
        dashboard, sort_keys=False, allow_unicode=True, default_flow_style=False, width=1000
    )
    OUT_YAML.write_text(BANNER + body)
    tabs = 1 + len(dashboard["tabs"])
    components = len(dashboard["main_dashboard"]["components"]) + sum(
        len(t["components"]) for t in dashboard["tabs"]
    )
    print(f"wrote {OUT_YAML.relative_to(HERE.parents[3])}: {tabs} tabs, {components} components")
    return 0


if __name__ == "__main__":
    sys.exit(main())
