def interactive(
    index: str,
    section: str,
    group: str | None,
    kind: str,
    column: str,
    column_type: str,
    title: str,
    icon: str,
    color: str,
    y: int,
    h: int,
) -> dict[str, Any]:
    comp: dict[str, Any] = {
        "component_type": "interactive",
        "workflow_tag": "ampliseq",
        "data_collection_tag": "metadata",
        "interactive_component_type": kind,
        "column_name": column,
        "column_type": column_type,
        "display": {"title_size": "md", "custom_color": color, "icon_name": icon},
        "title_align": "left",
        "placement": "left",
        "section": section,
        "tag": f"interactive-{index}",
        "index": index,
        "layout": {"x": 0, "y": y, "w": 1, "h": h},
        "title": title,
    }
    if group:
        comp["group"] = group
    return comp


def text(index: str, section: str, title: str, body: str, x, y, w, h) -> dict[str, Any]:
    return {
        "component_type": "text",
        "workflow_tag": "ampliseq",
        "title_size": "sm",
        "title_align": "left",
        "order": 2,
        "alignment": "left",
        "section": section,
        "tag": f"text-{index}",
        "index": index,
        "layout": {"x": x, "y": y, "w": w, "h": h},
        "title": title,
        "body": body,
    }


def card(
    index: str,
    section: str,
    dc: str,
    aggregation: str,
    column: str,
    column_type: str,
    title: str,
    icon: str,
    color: str,
    x,
    y,
    extra: dict[str, Any] | None = None,
) -> dict[str, Any]:
    comp: dict[str, Any] = {
        "component_type": "card",
        "workflow_tag": "ampliseq",
        "data_collection_tag": dc,
        "aggregation": aggregation,
        "column_name": column,
        "column_type": column_type,
    }
    comp.update(extra or {})
    comp.update(
        {
            "display": {
                "icon_name": icon,
                "icon_color": color,
                "title_color": color,
                "title_font_size": "xl",
                "value_font_size": "xl",
            },
            "title_size": "sm",
            "title_align": "left",
            "section": section,
            "tag": f"card-{index}",
            "index": index,
            # h=2 like every other shipped card: the viewer measures what the
            # content actually needs and grows the row when a breakdown asks
            # for more, so a stored 3 only ever left a blank band.
            "layout": {"x": x, "y": y, "w": 2, "h": 2},
            "title": title,
        }
    )
    return comp


def code_figure(
    index: str,
    section: str,
    dc: str,
    title: str,
    code: str,
    x,
    y,
    w,
    h,
    selection_column: str | None = None,
) -> dict[str, Any]:
    """A code-mode figure, optionally feeding the Analysis panel.

    ``selection_column`` only makes sense for a figure whose points are rows
    rather than aggregates, and it is only half the wiring: the reader takes the
    id from ``customdata[0]``, which on this path comes from a ``custom_data=``
    argument in the code itself. Setting the key without that argument yields a
    lasso that selects nothing at all, silently.
    """
    comp: dict[str, Any] = {
        "component_type": "figure",
        "workflow_tag": "ampliseq",
        "data_collection_tag": dc,
        "mode": "code",
        "code_content": code.strip() + "\n",
        "title_size": "sm",
        "title_align": "left",
        "section": section,
        "tag": f"figure-{index}",
        "index": index,
        "layout": {"x": x, "y": y, "w": w, "h": h},
        "title": title,
    }
    if selection_column:
        comp["selection_enabled"] = True
        comp["selection_column"] = selection_column
    return comp


def _colors_literal() -> str:
    return repr(HABITAT_COLORS)


