def load_reference_vars() -> dict[str, str]:
    """The variables `template.reference.vars` pins, minus the file paths."""
    template = yaml.safe_load(TEMPLATE_YAML.read_text())
    pinned = template["template"]["reference"]["vars"]
    return {k: v for k, v in pinned.items() if not str(v).startswith("{DATA_ROOT}")}


def substitute(node: Any, variables: dict[str, str]) -> Any:
    if isinstance(node, dict):
        return {k: substitute(v, variables) for k, v in node.items()}
    if isinstance(node, list):
        return [substitute(v, variables) for v in node]
    if isinstance(node, str):
        for name in _VAR.findall(node):
            if name not in variables:
                raise SystemExit(
                    f"reference.vars does not pin {{{name}}}, which base.yaml uses: {node!r}"
                )
            node = node.replace(f"{{{name}}}", variables[name])
        return node
    return node


