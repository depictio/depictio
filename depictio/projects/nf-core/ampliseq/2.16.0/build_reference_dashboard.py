#!/usr/bin/env python
"""Generate ``dashboards/reference_extended.yaml`` from ``dashboards/base.yaml``.

``base.yaml`` is the generic nf-core template. It may only bind columns that any
ampliseq run has, which rules out a map, a date range and environmental filters:
a real run without ``latitude`` would not be pruned, it would render a red
``Map error`` annotation in an HTTP 200 figure (``render_map``), because the
component pruner is DC-granular and never inspects columns.

The reference project shipped in this repo *does* have those columns, so its demo
dashboard can use them. Rather than fork ``base.yaml`` into a second 2000-line
file that drifts, this applies the demo layer on top of it:

    base.yaml  --(this script)-->  reference_extended.yaml  --(import)--> seeds

``reference_extended.yaml`` is generated and committed, never hand-edited.
``depictio/tests/models/test_ampliseq_reference_dashboard.py`` rebuilds it in
memory and fails when the committed file drifts from its source.

Template variables are resolved here (from ``template.reference.vars``), so the
output is a concrete dashboard rather than a template: ``depictio dashboard
import`` performs no substitution of its own.

Run:
    python depictio/projects/nf-core/ampliseq/2.16.0/build_reference_dashboard.py
"""

