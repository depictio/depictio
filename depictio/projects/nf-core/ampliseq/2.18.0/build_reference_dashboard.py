def annotate_heatmap_columns(dashboard: dict[str, Any], group_col: str, id_col: str) -> None:
    """Give every clustered heatmap a habitat strip above its columns.

    Both heatmaps have samples for columns, and nothing on either says which
    habitat a column came from: the clustering visibly groups the samples, and
    the reader has no way to check that the groups it found are the habitats.
    The row annotation cannot answer that, because `row_annotation_cols` reads
    columns of the heatmap's own DC and habitat lives in the metadata.

    base.yaml cannot carry this: `col_annotations` is a literal
    ``{column_label: category}`` map, so it names this run's samples. That is
    exactly the kind of run-specific value the demo layer exists for. The
    strip's colours come from the family's category colours.
    """
    metadata = Path(__file__).parent / "input" / "Metadata_full.tsv"
    with metadata.open(encoding="utf-8") as handle:
        rows = list(csv.DictReader(handle, delimiter="\t"))
    by_sample = {r[id_col]: r[group_col] for r in rows if r.get(id_col) and r.get(group_col)}
    if not by_sample:
        raise SystemExit(f"no {id_col}/{group_col} pairs in {metadata}")

    for tab in [dashboard["main_dashboard"], *dashboard.get("tabs", [])]:
        for comp in tab.get("components", []):
            cfg = comp.get("config") or {}
            if cfg.get("viz_kind") != "complex_heatmap":
                continue
            cfg["col_annotations"] = {group_col: dict(by_sample)}
            print(f"  {group_col} column strip on {comp.get('index', comp.get('tag'))}")


def add_tree_group_colour(dashboard: dict[str, Any]) -> None:
    """Offer the tree's dominant-group column as a tip colour.

    The tip-metadata recipe names that column ``dominant_habitat`` after the
    reference study's design, so base.yaml cannot list it: on another run the
    option would name a design the run does not have. The reference run is
    exactly that design, so the demo layer puts the option back.
    """
    for tab in [dashboard["main_dashboard"], *dashboard.get("tabs", [])]:
        for comp in tab.get("components", []):
            cfg = comp.get("config") or {}
            if cfg.get("viz_kind") != "phylogenetic":
                continue
            cols = cfg.setdefault("extra_color_cols", [])
            if "dominant_habitat" not in cols:
                cols.append("dominant_habitat")
                print(f"  dominant_habitat colour on {comp.get('index', comp.get('tag'))}")


def list_demo_tabs(main: dict[str, Any], titles: list[str]) -> None:
    """Name the demo tabs in the Overview's tab tiles, under "Data & QC".

    base.yaml lists only the tabs every run can have; the reference run also
    has the two demo tabs, which would otherwise be reachable from the sidebar
    alone.
    """
    for comp in main["components"]:
        body = comp.get("body") or ""
        if comp.get("index") != "ov-how-to-read" or "### Data & QC" not in body:
            continue
        head, rest = body.split("### Data & QC\n", 1)
        lines = rest.split("\n")
        end = next(i for i, line in enumerate(lines) if not line.startswith("- "))
        lines[end:end] = [f"- [{title}](tab:{title})" for title in titles]
        comp["body"] = head + "### Data & QC\n" + "\n".join(lines)
        return
    raise SystemExit("no Data & QC tab list on the Overview")


def insert_after_group(dashboard: dict[str, Any], group: str, new_tabs: list[dict]) -> None:
    """Add ``new_tabs`` at the end of tab group ``group``, shifting the tabs after it.

    `tab_order` stays contiguous within each group (RULES.md, Family), so the
    demo tabs join "Data & QC" right after MultiQC and every later tab moves
    down by as many slots. The list itself stays base tabs first: the import
    matches tabs by title, and `tab_order` alone sets the display order.
    """
    last = max(t.get("tab_order", 0) for t in dashboard["tabs"] if t.get("tab_group") == group)
    for tab in dashboard["tabs"]:
        if tab.get("tab_order", 0) > last:
            tab["tab_order"] += len(new_tabs)
    for offset, tab in enumerate(new_tabs, start=1):
        tab["tab_order"] = last + offset
    dashboard["tabs"].extend(new_tabs)


GRID_COLS = 8


def fit_text_tiles(dashboard: dict[str, Any]) -> None:
    """Raise a text tile shorter than its body needs, then close the gap.

    The viewer autofits text tiles at render (TextRenderer measures its content
    and DashboardGrid turns that into rows), so this is only the stored floor
    that decides the first paint: half the shared estimate, the shipped-YAML
    lint's rule for an autofit tile. Tiles already tall enough are left alone.

    Re-packs a touched section afterwards so a raised tile does not overlap its
    neighbour in the stored layout. Route alternates share one slot (same
    layout), so they move together; filter-bar controls render in the bar, not
    the grid, and are not packed.

    Section-scoped because DashboardGrid mounts one ResponsiveGridLayout per
    section, so y is section-relative.
    """
    raised = 0
    for tab in [dashboard["main_dashboard"], *dashboard.get("tabs", [])]:
        left = {s.get("name") for s in (tab.get("filter_sections") or [])}
        buckets: dict[Any, list] = {}
        touched: set = set()
        for comp in tab.get("components", []):
            if comp.get("component_type") == "interactive" or comp.get("section") in left:
                continue
            layout = comp.get("layout")
            if not isinstance(layout, dict):
                continue
            slot = (layout["x"], layout["y"], layout["w"], layout["h"])
            if comp.get("component_type") == "text":
                need = math.ceil(estimate_text_rows(comp.get("body") or "", layout["w"]) / 2)
                if layout["h"] < need:
                    layout["h"] = need
                    touched.add(comp.get("section"))
                    raised += 1
            buckets.setdefault(comp.get("section"), []).append((slot, layout))
        for name, items in buckets.items():
            if name not in touched:
                continue
            heights = [0] * GRID_COLS
            placed: dict[tuple, int] = {}
            for slot, item in sorted(items, key=lambda pair: (pair[0][1], pair[0][0])):
                if slot not in placed:
                    span = range(item["x"], min(item["x"] + item["w"], GRID_COLS))
                    placed[slot] = max((heights[c] for c in span), default=0)
                    for col in span:
                        heights[col] = max(heights[col], placed[slot] + item["h"])
                item["y"] = placed[slot]
    print(f"  fit text tiles: {raised} raised")


def build() -> dict[str, Any]:
    variables = load_reference_vars()
    dashboard = substitute(yaml.safe_load(BASE_YAML.read_text()), variables)
    dashboard = copy.deepcopy(dashboard)

    group_col = variables["GROUP_COL"]
    group_display = variables["GROUP_COL_DISPLAY"]
    id_col = variables["METADATA_ID_COL"]

    annotate_heatmap_columns(dashboard, group_col, id_col)
    add_tree_group_colour(dashboard)

    main = dashboard["main_dashboard"]
    main["title"] = "nf-core/ampliseq"
    main["subtitle"] = "Ammer catchment reference dataset: QC, diversity, campaign and environment"
    main_tab_layer(main, group_col, id_col)

    insert_after_group(
        dashboard,
        "Data & QC",
        [
            sampling_campaign_tab(group_col, group_display, id_col, 0),
            environment_tab(group_col, group_display, id_col, 0),
        ],
    )

    list_demo_tabs(main, ["Sampling Campaign", "Environment (CTD)"])

    # Last, so it also covers the two tabs added just above.
    fit_text_tiles(dashboard)
    return dashboard


def main() -> int:
    dashboard = build()
    body = yaml.safe_dump(
        dashboard, sort_keys=False, allow_unicode=True, default_flow_style=False, width=1000
    )
    OUT_YAML.write_text(BANNER + body)
    tabs = 1 + len(dashboard["tabs"])
    components = len(dashboard["main_dashboard"]["components"]) + sum(
        len(t["components"]) for t in dashboard["tabs"]
    )
    print(f"wrote {OUT_YAML.relative_to(HERE.parents[3])}: {tabs} tabs, {components} components")
    return 0


if __name__ == "__main__":
    sys.exit(main())
