def interactive(
    index: str,
    section: str,
    group: str | None,
    kind: str,
    column: str,
    column_type: str,
    title: str,
    icon: str,
    color: str,
    y: int,
    h: int,
) -> dict[str, Any]:
    comp: dict[str, Any] = {
        "component_type": "interactive",
        "workflow_tag": "ampliseq",
        "data_collection_tag": "metadata",
        "interactive_component_type": kind,
        "column_name": column,
        "column_type": column_type,
        # A Mantine palette name, one per column across the dashboard, so a
        # filter reads as the same filter wherever it appears.
        "display": {"icon_name": icon, "custom_color": color},
        "section": section,
        "tag": f"am-ref-filter-{index}",
        "index": index,
        "layout": {"x": 0, "y": y, "w": 1, "h": h},
        "title": title,
    }
    if group:
        comp["group"] = group
    return comp


def card(
    index: str,
    section: str,
    column: str,
    aggregation: str,
    title: str,
    icon: str,
    color: str,
    description: str,
    x: int,
    w: int,
    extra: dict[str, Any] | None = None,
) -> dict[str, Any]:
    """A strip card on the metadata DC; the section's `card_variant` styles it."""
    comp: dict[str, Any] = {
        "component_type": "card",
        "workflow_tag": "ampliseq",
        "data_collection_tag": "metadata",
        "aggregation": aggregation,
        "column_name": column,
        "column_type": "float64" if aggregation == "median" else "object",
    }
    comp.update(extra or {})
    comp.update(
        {
            "display": {"icon_name": icon, "icon_color": color},
            "section": section,
            "tag": f"am-ref-card-{index}",
            "index": index,
            "title": title,
            "description": description,
            "layout": {"x": x, "y": 0, "w": w, "h": 1},
        }
    )
    return comp


def code_figure(
    index: str,
    section: str,
    dc: str,
    title: str,
    code: str,
    x,
    y,
    w,
    h,
    selection_column: str | None = None,
) -> dict[str, Any]:
    """A code-mode figure, optionally feeding the Analysis panel.

    ``selection_column`` only makes sense for a figure whose points are rows
    rather than aggregates, and it is only half the wiring: the reader takes the
    id from ``customdata[0]``, which on this path comes from a ``custom_data=``
    argument in the code itself. Setting the key without that argument yields a
    lasso that selects nothing at all, silently.
    """
    comp: dict[str, Any] = {
        "component_type": "figure",
        "workflow_tag": "ampliseq",
        "data_collection_tag": dc,
        "mode": "code",
        "code_content": code.strip() + "\n",
        "section": section,
        "tag": f"am-ref-figure-{index}",
        "index": index,
        "layout": {"x": x, "y": y, "w": w, "h": h},
        "title": title,
    }
    if selection_column:
        comp["selection_enabled"] = True
        comp["selection_column"] = selection_column
    return comp


def _group_colors(group_col: str) -> str:
    """The code-figure preamble every demo figure shares (RULES.md, Colours).

    Colours by Analysis mode's groups when there are some, else by the
    pipeline's group column in the family's category colours. The figures name
    their own `color`, so they take the pieces of `depictio_group_kwargs`
    rather than spreading it.
    """
    return (
        f"grp_col = depictio_group_by[0] if depictio_group_by else '{group_col}'\n"
        "colors = depictio_group_kwargs.get('color_discrete_map') or "
        f"depictio_category_colors.get('{group_col}') or {{}}\n"
    )


