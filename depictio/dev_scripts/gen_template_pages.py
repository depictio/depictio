"""Generate the nf-core template docs pages, catalog cards and index rows.

A page joins three sources, each owning what it is the authority on:

- ``template.yaml`` and the recipes: the reference tables, which
  ``gen_template_docs`` renders into ``_generated/<pipeline>-latest.md`` and
  the page includes;
- the dashboard YAML: tab titles, icons, colours, sections, filters and
  components, rendered here into each tab block;
- ``docs/page.yaml`` next to the template (``TemplateDocs``): the prose only a
  person can write, from the question each tab answers to the validation runs.

The same ``page.yaml`` drives the status badge, the catalog card in
``pipeline-templates/README.md`` and the row in ``nf-core/index.md``, so the
status and the blurbs are written once. A template whose ``page.yaml`` sets
``generate_page: false`` keeps a hand-written page; its card and row are still
generated.

Only the highest version directory of each pipeline is read (the one
``nf-core/<pipeline>/latest`` resolves to); older versions appear in the version
picker. Pipelines without a ``docs/page.yaml`` are left alone.

Usage:
    python -m depictio.dev_scripts.gen_template_pages --docs-root /path/to/depictio-docs
    python -m depictio.dev_scripts.gen_template_pages --check        # CI / pre-commit
    python -m depictio.dev_scripts.gen_template_pages --pipeline riboseq
"""

