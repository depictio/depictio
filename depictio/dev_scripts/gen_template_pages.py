def _indent(text: str, level: int = 1) -> str:
    return textwrap.indent(text.strip("\n"), "    " * level, lambda line: bool(line.strip()))


def _block(text: str | None) -> list[str]:
    """A Markdown field as page lines followed by a blank line (nothing if empty)."""
    return [text.strip("\n"), ""] if text and text.strip() else []


def _slug(title: str) -> str:
    """Screenshot slug: lowercase, words joined by underscores (MultiQC -> multiqc)."""
    return "_".join(re.findall(r"[a-z0-9]+", title.lower()))


def _material_icon(icon: str | None) -> str | None:
    """``mdi:chart-bar`` -> ``material-chart-bar`` (None for image paths)."""
    if not icon or not icon.startswith("mdi:"):
        return None
    name = icon.removeprefix("mdi:")
    return f"material-{_ICON_ALIASES.get(name, name)}"


def _is_multiqc_tab(tab: DashboardTab) -> bool:
    return "multiqc" in (tab.icon or "").lower() or tab.title == "MultiQC"


def _tab_header(tab: DashboardTab) -> str:
    if _is_multiqc_tab(tab):
        return _MULTIQC_HEADER
    icon = _material_icon(tab.icon)
    if not icon:
        return tab.title
    colour = f"{{ .mc-{tab.colour} }}" if tab.colour in _DOC_COLOURS else ""
    return f":{icon}:{colour} {tab.title}"


def _bullet_icon(tab: DashboardTab) -> str:
    if _is_multiqc_tab(tab):
        return ":material-chart-box-outline:"
    icon = _material_icon(tab.icon)
    return f":{icon}:" if icon else ":material-tab:"


def _callouts(docs: TemplateDocs, position: CalloutPosition) -> list[str]:
    lines: list[str] = []
    for callout in docs.callouts:
        if callout.position == position:
            lines += [_render_callout(callout), ""]
    return lines


def _render_callout(callout: DocsCallout) -> str:
    return f'!!! {callout.kind} "{callout.title}"\n{_indent(callout.body)}'


def _person(handle: str) -> str:
    return (
        f'    <a class="tpl-person" href="https://github.com/{handle}" target="_blank" '
        f'rel="noopener">\n'
        f'      <img src="https://github.com/{handle}.png?size=80" alt="" loading="lazy"> '
        f"{handle}\n    </a>"
    )


def _logo_imgs(pipeline: str, indent: str) -> str:
    base = f"https://raw.githubusercontent.com/nf-core/{pipeline}/master/docs/images"
    return (
        f'{indent}<img class="nf-core-dark" src="{base}/nf-core-{pipeline}_logo_dark.png" '
        f'alt="nf-core/{pipeline}">\n'
        f'{indent}<img class="nf-core-light" src="{base}/nf-core-{pipeline}_logo_light.png" '
        f'alt="nf-core/{pipeline}">'
    )


