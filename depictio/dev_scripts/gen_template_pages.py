def _screenshot_lines(p: PipelineDocs, tab: DocsDashboardTab, images_dir: Path) -> list[str]:
    slug = tab.image or _slug(tab.title)
    rel = f"../../images/pipeline-templates/nf-core/{p.pipeline}/{slug}"
    light = images_dir / p.pipeline / f"{slug}_light.png"
    dark = images_dir / p.pipeline / f"{slug}_dark.png"
    if not light.is_file():
        return []
    attrs = '{ .tpl-shot target="_blank" rel="noopener" }'
    if not dark.is_file():
        return [
            f"[![{tab.title} dashboard]({rel}_light.png){{ loading=lazy }}]"
            f"({rel}_light.png){attrs}",
            "",
        ]
    return [
        f"[![{tab.title} dashboard]({rel}_light.png#only-light){{ loading=lazy }}]"
        f"({rel}_light.png){attrs}",
        "",
        f"[![{tab.title} dashboard]({rel}_dark.png#only-dark){{ loading=lazy }}]"
        f"({rel}_dark.png){attrs}",
        "",
    ]


def _render_tab(p: PipelineDocs, tab: DashboardTab, images_dir: Path) -> list[str]:
    prose = next(t for t in p.docs.tabs if t.title == tab.title)
    body: list[str] = [f"*{prose.question.strip()}*", ""]
    body += _block(prose.conditional)
    body += _screenshot_lines(p, prose, images_dir)
    body += _block(prose.description)
    inner = [prose.filters.strip() if prose.filters else render_filters_line(tab), ""]
    inner += render_components_table(tab)
    body += ['??? abstract ":material-tune-variant: Filters and components"', ""]
    body += [_indent("\n".join(inner)), ""]
    body += _block(prose.after)
    return [f'=== "{_tab_header(tab)}"', "", _indent("\n".join(body)), ""]


def _use_count_line(p: PipelineDocs) -> list[str]:
    components = [
        c
        for tab in p.tabs
        for c in tab.raw.get("components") or []
        if c.get("component_type") != "text"
    ]
    with_use = sum(1 for c in components if c.get("use"))
    if not with_use:
        return []
    return [
        f"{with_use} of its {len(components)} components carry a `use:` catalog reference, "
        "so a tile says where its panel comes from.",
        "",
    ]


def render_page(p: PipelineDocs, docs_dir: Path) -> str:
    d = p.docs
    status = d.status
    source = (p.template_dir / _PAGE_YAML).relative_to(_REPO_ROOT)
    images_dir = docs_dir / _IMAGES_SUBDIR

    options = "\n".join(
        f'    <option value="{v}"{" selected" if v == p.version else ""}>{v}</option>'
        for v in p.versions
    )
    lines = [
        "---",
        f"title: {d.page_title}",
        "hide:",
        "  - navigation",
        "---",
        "",
        _GEN_NOTE.format(source=source),
        "",
        '<div class="template-banner">',
        f'  <a class="template-banner-logo" href="https://nf-co.re/{p.pipeline}" '
        f'target="_blank" title="nf-core/{p.pipeline} on nf-co.re">',
        _logo_imgs(p.pipeline, "    "),
        "  </a>",
        '  <div class="template-banner-body">',
        f'    <h1 class="template-title">{d.page_title}</h1>',
        f'    <p class="template-subtitle">{(d.subtitle or "").strip()}</p>',
        '    <p class="template-links">',
        f'      <a href="https://nf-co.re/{p.pipeline}" target="_blank">'
        '<i class="mdi mdi-open-in-new"></i> nf-co.re</a>',
        f'      <a href="https://github.com/nf-core/{p.pipeline}" target="_blank">'
        '<i class="mdi mdi-github"></i> GitHub</a>',
        "    </p>",
        "  </div>",
        f'  <span class="template-status-{status.value} template-banner-badge" '
        f'data-tooltip="{_STATUS_TOOLTIP[status]}"><i class="mdi {_STATUS_ICON[status]}"></i> '
        f"{_STATUS_LABEL[status]}</span>",
        "</div>",
        "",
        f'<div class="tpl-version-pick" data-latest="{p.version}">',
        '  <span class="tpl-version-icon"><i class="mdi mdi-source-branch"></i></span>',
        '  <span class="tpl-version-label">Template version</span>',
        '  <select id="tpl-version" class="tpl-version-select" aria-label="Template version">',
        options,
        "  </select>",
        '  <span class="tpl-version-badge">latest</span>',
        "</div>",
        "",
        *_block(d.intro),
    ]
    bullets = [
        f"- {_bullet_icon(tab)} **{tab.title}**: {(prose.summary or '').strip()}"
        for tab in p.tabs
        for prose in d.tabs
        if prose.title == tab.title and prose.summary
    ]
    lines += [*bullets, "", *_block(d.intro_after), *_callouts(d, CalloutPosition.INTRO)]

    # Quick start
    run_cmd = [
        "depictio run \\",
        f"  --template nf-core/{p.pipeline}/latest \\",
        f"  --data-root /path/to/{p.pipeline}_results" + (" \\" if d.run_vars else ""),
    ]
    run_cmd += [
        f"  --var {var}" + (" \\" if i < len(d.run_vars) - 1 else "")
        for i, var in enumerate(d.run_vars)
    ]
    first_tab = ["```bash", *run_cmd, "```", "", (d.quick_start or "").strip("\n")]
    lines += [
        "---",
        "",
        "## :material-rocket-launch-outline: Quick start",
        "",
        '=== "Point at a finished run"',
        "",
        _indent("\n".join(first_tab)),
        "",
    ]
    for extra in d.quick_start_tabs:
        lines += [f'=== "{extra.label}"', "", _indent(extra.body), ""]
    trigger = [
        "```bash",
        "depictio-cli config nextflow --install     # once per machine",
        f"nextflow run nf-core/{p.pipeline} -r {p.version} -profile docker --outdir results",
        "```",
        "",
        "No `depictio run`, and no template named: the pipeline ingests its own",
        "output directory when it finishes and resolves this template from its own",
        "manifest. See [Nextflow trigger](../../depictio-cli/nextflow-trigger.md).",
    ]
    lines += [
        '=== "From the pipeline itself (v1.10.0+)"',
        "",
        _indent("\n".join(trigger)),
        "",
        *_callouts(d, CalloutPosition.QUICK_START),
    ]

    # Reference
    lines += [
        "---",
        "",
        "## :material-book-open-variant: Reference",
        "",
        *_block(d.reference),
        *_use_count_line(p),
        _SELF_ADAPTING,
        "",
        *_callouts(d, CalloutPosition.REFERENCE),
        f'<div class="tpl-version-block" data-version="{p.version}" markdown>',
        "",
        f'--8<-- "pipeline-templates/nf-core/_generated/{p.pipeline}-latest.md"',
        "",
        "</div>",
        "",
    ]

    # Dashboard tabs
    lines += [
        "---",
        "",
        "## :material-view-dashboard-outline: Dashboard tabs",
        "",
        *_block(d.tabs_intro),
    ]
    for tab in p.tabs:
        lines += _render_tab(p, tab, images_dir)
    lines += _callouts(d, CalloutPosition.TABS)

    # Running, data structure, validation
    for icon, heading, text, position in (
        ("play-circle-outline", "Running the pipeline", d.running, CalloutPosition.RUNNING),
        (
            "folder-open-outline",
            "Required data structure",
            d.data_structure,
            CalloutPosition.DATA_STRUCTURE,
        ),
        ("flask-outline", "Validation runs", d.validation, CalloutPosition.VALIDATION),
    ):
        lines += ["---", "", f"## :material-{icon}: {heading}", "", *_block(text)]
        lines += _callouts(d, position)

    # Resources and authorship
    resources = [
        (
            f"nf-co.re/{p.pipeline}",
            f"https://nf-co.re/{p.pipeline}",
            "official pipeline documentation",
        ),
        (
            f"nf-co.re/{p.pipeline}/{p.version}/results",
            f"https://nf-co.re/{p.pipeline}/{p.version}/results",
            "AWS test results",
        ),
        (
            "Template System Reference",
            "../../usage/projects/templates.md",
            "YAML format, variables, conditionals",
        ),
        ("Recipes", "../../usage/projects/recipes.md", "how to read, test, and write recipes"),
        *((r.label, r.url, r.note) for r in d.resources),
    ]
    lines += [
        "---",
        "",
        "## :material-link-variant: Additional resources",
        "",
        *(f"- [{label}]({url}): {note}" for label, url, note in resources),
        "",
        "---",
        "",
        "## :material-account-group-outline: Authorship",
        "",
        *_render_authorship(p),
        "",
        "Reviewing a template on your own data, or taking over a role here, is a",
        "contribution in itself: the [contributing guide](../../developer/contributing-templates.md)",
        "says what each one involves.",
    ]
    text = "\n".join(lines)
    return re.sub(r"\n{3,}", "\n\n", text).rstrip() + "\n"


def _render_authorship(p: PipelineDocs) -> list[str]:
    a = p.docs.authorship
    roles = [
        ("mdi-code-braces", "Developers", "Wrote the template, its recipes and its dashboards.",
         a.developers),
        ("mdi-eye-check-outline", "Reviewers", _REVIEWER_NOTE[p.docs.status], a.reviewers),
        ("mdi-wrench-outline", "Maintainers", f"Keep it working as nf-core/{p.pipeline} releases.",
         a.maintainers),
    ]  # fmt: skip
    lines = ['<div class="tpl-credits">']
    for icon, role, note, handles in roles:
        lines += [
            '  <div class="tpl-credit">',
            f'    <span class="tpl-credit-role"><i class="mdi {icon}"></i> {role}</span>',
            f'    <span class="tpl-credit-note">{note}</span>',
        ]
        if handles:
            lines += [_person(h) for h in handles]
        else:
            lines.append(
                '    <span class="tpl-person"><i class="mdi mdi-account-plus-outline"></i> Open</span>'
            )
        lines.append("  </div>")
    lines.append("</div>")
    return lines


