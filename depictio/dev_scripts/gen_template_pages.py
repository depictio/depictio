def load_pipeline(pipeline_dir: Path) -> PipelineDocs | None:
    """Load the latest version of a pipeline, or None when it has no page.yaml."""
    versions = sorted(_template_versions(pipeline_dir), key=_version_key, reverse=True)
    if not versions:
        return None
    template_dir = pipeline_dir / versions[0]
    page_yaml = template_dir / _PAGE_YAML
    if not page_yaml.is_file():
        return None
    docs = TemplateDocs(**(_load_yaml(str(page_yaml)) or {}))
    raw_template = _load_yaml(str(template_dir / "template.yaml"))
    meta = TemplateMetadata(**raw_template["template"])
    if not meta.dashboards:
        raise DocsError(f"{template_dir}: template.yaml lists no dashboards")
    dashboard = _load_yaml(str(template_dir / meta.dashboards[0]))
    pipeline = PipelineDocs(
        pipeline=pipeline_dir.name,
        version=versions[0],
        versions=versions,
        template_dir=template_dir,
        docs=docs,
        meta=meta,
        dashboard=dashboard,
    )
    pipeline.tabs = _dashboard_tabs(dashboard)
    if docs.generate_page:
        _check_tab_coverage(pipeline)
    return pipeline


def _dashboard_tabs(dashboard: dict[str, Any]) -> list[DashboardTab]:
    main = dashboard.get("main_dashboard") or {}
    tabs = [
        DashboardTab(
            title=main.get("main_tab_name") or "Main",
            icon=main.get("tab_icon"),
            colour=main.get("tab_icon_color"),
            is_main=True,
            raw=main,
        )
    ]
    children = sorted(dashboard.get("tabs") or [], key=lambda t: t.get("tab_order", 0))
    tabs += [
        DashboardTab(
            title=t["title"],
            icon=t.get("tab_icon"),
            colour=t.get("tab_icon_color"),
            is_main=False,
            raw=t,
        )
        for t in children
    ]
    return tabs


def _check_tab_coverage(p: PipelineDocs) -> None:
    """Every dashboard tab has prose and every prose block names a real tab."""
    dash = [t.title for t in p.tabs]
    docs = [t.title for t in p.docs.tabs]
    missing = [t for t in dash if t not in docs]
    unknown = [t for t in docs if t not in dash]
    if missing or unknown:
        raise DocsError(
            f"{p.template_dir / _PAGE_YAML}: tabs out of sync with {p.meta.dashboards[0]}"
            f" (missing: {missing or '-'}; not in the dashboard: {unknown or '-'})"
        )


