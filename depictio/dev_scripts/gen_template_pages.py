def render_card(p: PipelineDocs) -> str:
    d = p.docs
    status = d.status
    keywords = " ".join(d.keywords)
    return "\n".join(
        [
            f'  <a class="template-card" href="nf-core/{p.pipeline}/" '
            f'data-tpl-name="nf-core/{p.pipeline}" data-tpl-status="{status.value}" '
            f'data-tpl-version="{p.version}" data-tpl-keywords="{keywords}">',
            '    <div class="template-card-logo">',
            _logo_imgs(p.pipeline, "      "),
            "    </div>",
            '    <div class="template-card-body">',
            f'      <p class="template-card-desc">{d.card_blurb.strip()}</p>',
            '      <div class="template-card-meta">',
            f'        <span class="template-version">v{p.version}</span>',
            f'        <span class="template-status-{status.value}"><i class="mdi '
            f'{_STATUS_ICON[status]}" style="vertical-align:-1px;"></i> '
            f"{_STATUS_LABEL[status]}</span>",
            "      </div>",
            "    </div>",
            "  </a>",
        ]
    )


def render_index_row(p: PipelineDocs) -> str:
    versions = ", ".join(sorted(p.versions, key=_version_key))
    return f"| [{p.pipeline}]({p.pipeline}.md) | {p.docs.index_summary} | {versions} |"


def _card_span(text: str, pipeline: str) -> tuple[int, int] | None:
    match = re.search(
        rf'  <a class="template-card" href="nf-core/{re.escape(pipeline)}/".*?</a>', text, re.S
    )
    return match.span() if match else None


def update_catalog(text: str, pipelines: list[PipelineDocs]) -> str:
    """Replace each pipeline's card in place; append new ones after the last nf-core card."""
    for p in pipelines:
        card = render_card(p)
        span = _card_span(text, p.pipeline)
        if span:
            text = text[: span[0]] + card + text[span[1] :]
            continue
        last = None
        for match in re.finditer(r'  <a class="template-card" href="nf-core/.*?</a>', text, re.S):
            last = match
        if last is None:
            raise DocsError("no nf-core card found in the catalog page to append after")
        text = text[: last.end()] + "\n\n" + card + text[last.end() :]
    return text


def update_index(text: str, pipelines: list[PipelineDocs]) -> str:
    """Replace each pipeline's row in place; append new ones after the last row."""
    lines = text.split("\n")
    for p in pipelines:
        row = render_index_row(p)
        prefix = f"| [{p.pipeline}]({p.pipeline}.md) |"
        hits = [i for i, line in enumerate(lines) if line.startswith(prefix)]
        if hits:
            lines[hits[0]] = row
            continue
        rows = [
            i for i, line in enumerate(lines) if re.match(r"\| \[[^\]]+\]\([^)]+\.md\) \|", line)
        ]
        if not rows:
            raise DocsError("no template row found in the nf-core index to append after")
        lines.insert(rows[-1] + 1, row)
    return "\n".join(lines)


