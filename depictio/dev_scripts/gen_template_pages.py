def _write_or_check(path: Path, content: str, check: bool, root: Path, stale: list[str]) -> None:
    existing = path.read_text() if path.is_file() else None
    rel = path.relative_to(root)
    if existing == content:
        if not check:
            print(f"unchanged  {rel}")
        return
    if check:
        stale.append(str(rel))
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content)
    print(f"wrote      {rel}")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--templates-root", default=str(_DEFAULT_TEMPLATES_ROOT))
    parser.add_argument(
        "--docs-root",
        default=None,
        help="depictio-docs repo root (auto-detected as a sibling checkout when omitted).",
    )
    parser.add_argument("--pipeline", action="append", help="Limit to these pipelines.")
    parser.add_argument(
        "--check", action="store_true", help="Fail (exit 1) if anything is stale, without writing."
    )
    args = parser.parse_args(argv)

    templates_root = Path(args.templates_root).expanduser().resolve()
    docs_root = _find_docs_root(args.docs_root)
    docs_dir = docs_root / "docs"

    pipelines: list[PipelineDocs] = []
    errors: list[str] = []
    for pipeline_dir in sorted(p for p in templates_root.iterdir() if p.is_dir()):
        if args.pipeline and pipeline_dir.name not in args.pipeline:
            continue
        try:
            loaded = load_pipeline(pipeline_dir)
        except Exception as exc:  # noqa: BLE001 — report every broken page.yaml at once
            errors.append(f"{pipeline_dir.name}: {exc}")
            continue
        if loaded:
            pipelines.append(loaded)
    if errors:
        print("Invalid page.yaml:", *errors, sep="\n  ")
        return 1

    problems = [msg for p in pipelines for msg in lint_pipeline(p, docs_root)]
    for msg in problems:
        print(f"warning    {msg}")

    stale: list[str] = []
    for p in pipelines:
        if p.docs.generate_page:
            page = docs_dir / _PAGES_SUBDIR / f"{p.pipeline}.md"
            _write_or_check(page, render_page(p, docs_dir), args.check, docs_root, stale)
    for rel, update in ((_CATALOG_PAGE, update_catalog), (_INDEX_PAGE, update_index)):
        path = docs_dir / rel
        _write_or_check(path, update(path.read_text(), pipelines), args.check, docs_root, stale)

    if args.check and stale:
        print("Stale template pages (run gen_template_pages to refresh):", *stale, sep="\n  ")
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
