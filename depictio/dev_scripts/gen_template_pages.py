def _material_icons_dir(docs_root: Path) -> Path | None:
    for candidate in sorted(docs_root.glob(".venv/lib/python*/site-packages")):
        icons = candidate / "material" / "templates" / ".icons" / "material"
        if icons.is_dir():
            return icons
    return None


def lint_pipeline(p: PipelineDocs, docs_root: Path) -> list[str]:
    """Problems that would render silently wrong: missing screenshots or icons."""
    problems = []
    images_dir = docs_root / "docs" / _IMAGES_SUBDIR / p.pipeline
    for prose in p.docs.tabs:
        slug = prose.image or _slug(prose.title)
        if not (images_dir / f"{slug}_light.png").is_file() and not prose.conditional:
            problems.append(f"{p.pipeline}: no screenshot {slug}_light.png for tab {prose.title!r}")
    icons_dir = _material_icons_dir(docs_root)
    if icons_dir:
        for tab in p.tabs:
            icon = _material_icon(tab.icon)
            if icon and not (icons_dir / f"{icon.removeprefix('material-')}.svg").is_file():
                problems.append(f"{p.pipeline}: icon {tab.icon} missing from the docs theme")
    return problems


