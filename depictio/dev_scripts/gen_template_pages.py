def _component_label(component: dict[str, Any]) -> str:
    title = component.get("title") or component.get("selected_plot")
    title = title or component.get("selected_module") or component.get("component_type", "")
    return f"*{title}*"


def _section_cell(components: list[dict[str, Any]]) -> str:
    cards = [c for c in components if c.get("component_type") == "card"]
    others = [c for c in components if c.get("component_type") != "card"]
    parts: list[str] = []
    if len(cards) == 1:
        parts.append(_component_label(cards[0]))
    elif cards:
        parts.append(f"{len(cards)} cards")
    parts += [_component_label(c) for c in others]
    return ", ".join(parts)


def _section_flags(section: dict[str, Any]) -> str:
    flags = []
    if section.get("collapsed"):
        flags.append("collapsed")
    if section.get("persistent") or section.get("pin"):
        flags.append("pinned")
    return f" ({', '.join(flags)})" if flags else ""


def render_components_table(tab: DashboardTab) -> list[str]:
    """Section rows in dashboard order; text tiles and filters are left out."""
    by_section: dict[str, list[dict[str, Any]]] = {}
    for component in tab.raw.get("components") or []:
        if component.get("component_type") in ("text", "interactive"):
            continue
        by_section.setdefault(component.get("section") or "", []).append(component)
    rows = []
    for section in tab.raw.get("grid_sections") or []:
        components = by_section.pop(section["name"], [])
        if components:
            rows.append(
                f"| {section['name']} | {_section_cell(components)}{_section_flags(section)} |"
            )
    for name, components in by_section.items():  # components outside a declared section
        rows.append(f"| {name or 'Ungrouped'} | {_section_cell(components)} |")
    if not rows:
        return []
    return ["| Section | What it holds |", "|---|---|", *rows]


_RANGE_TYPES = {"RangeSlider", "Slider"}


def _join(items: list[str]) -> str:
    """``a``, ``a and b``, ``a, b and c``."""
    return items[0] if len(items) == 1 else f"{', '.join(items[:-1])} and {items[-1]}"


def _article(word: str) -> str:
    return "an" if word[:1].lower() in "aeiou" else "a"


def _filter_name(component: dict[str, Any]) -> str:
    """Filter label in code, with ``{GROUP_COL_DISPLAY}`` shown as ``<GROUP_COL>``."""
    title = str(component.get("title") or component.get("column_name") or "")
    title = re.sub(r"\{([A-Z0-9_]+?)(?:_DISPLAY)?\}", r"<\1>", title)
    name = f"`{title}`"
    if component.get("interactive_component_type") in _RANGE_TYPES:
        name = f"{name} range"
    return name


def render_filters_line(tab: DashboardTab) -> str:
    """``**Filters** · `A` and `B` in a *Group* group; ...`` from the tab's own filters."""
    by_section: dict[str, list[str]] = {}
    for component in tab.raw.get("components") or []:
        if component.get("component_type") == "interactive":
            by_section.setdefault(component.get("section") or "", []).append(
                _filter_name(component)
            )
    parts = []
    for section in tab.raw.get("filter_sections") or []:
        names = by_section.pop(section["name"], [])
        if not names:
            continue
        where = ""
        if section.get("persistent"):
            pin = section.get("pin")
            where = f", on every tab{', pinned to the ' + pin if pin else ''}"
        group = section["name"]
        parts.append(f"{_join(names)} in {_article(group)} *{group}* group{where}")
    parts += [_join(names) for names in by_section.values()]
    if not parts:
        return "**Filters** · none of its own; the pinned filters of the first tab apply."
    return "**Filters** · " + "; ".join(parts) + "."


