@dataclass
class DashboardTab:
    """One tab of the dashboard YAML, reduced to what the page shows."""

    title: str
    icon: str | None
    colour: str | None
    is_main: bool
    raw: dict[str, Any]


@dataclass
class PipelineDocs:
    pipeline: str
    version: str
    versions: list[str]
    template_dir: Path
    docs: TemplateDocs
    meta: TemplateMetadata
    dashboard: dict[str, Any]
    tabs: list[DashboardTab] = field(default_factory=list)


class DocsError(Exception):
    """A page.yaml that disagrees with its template or dashboard."""


