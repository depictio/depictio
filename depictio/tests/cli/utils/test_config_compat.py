def _config_from_a_newer_server() -> dict:
    """A configuration a server one release ahead might write: unknown keys at
    the top level and inside user, its token, and s3_storage."""
    config = {
        "telemetry_hint": "opt-in",
        "deployment_notes": {"operator": "platform"},
        **VALID_CONFIG,
    }
    config["user"] = {**config["user"], "sso_provider": "okta"}
    config["user"]["token"] = {**config["user"]["token"], "mfa_bound": True}
    config["s3_storage"] = {**config["s3_storage"], "future_s3_setting": 42}
    return config


@pytest.fixture(autouse=True)
def reset_warnings():
    """Each test starts with no warning printed yet: the loader warns once per
    process, and without this the first test's warning would silence the rest."""
    config_compat._warned.clear()
    yield
    config_compat._warned.clear()


@pytest.fixture
def printed_warnings():
    """The warning lines config_compat printed, via rich."""
    with patch("depictio.cli.cli.utils.config_compat.rich_print_checked_statement") as rich_print:
        yield rich_print


class TestStripUnknownKeys:
    def test_unknown_keys_at_every_nesting_level_are_reported(self):
        cleaned, ignored = strip_unknown_cli_config_keys(_config_from_a_newer_server())

        assert ignored == [
            "deployment_notes",
            "s3_storage.future_s3_setting",
            "telemetry_hint",
            "user.sso_provider",
            "user.token.mfa_bound",
        ]
        # Everything the CLI knows is still there, untouched.
        assert cleaned["s3_storage"]["bucket"] == "depictio-bucket"
        assert cleaned["user"]["token"]["access_token"] == "access-token-example"

    def test_the_legacy_top_level_spellings_are_known(self):
        raw = {
            "base_url": VALID_CONFIG["api_base_url"],
            "s3": VALID_CONFIG["s3_storage"],
            "user": VALID_CONFIG["user"],
        }
        cleaned, ignored = strip_unknown_cli_config_keys(raw)

        assert ignored == []
        assert cleaned["base_url"] == raw["base_url"]
        assert cleaned["s3"] == raw["s3"]

    def test_aliased_and_mongo_keys_are_not_mistaken_for_unknowns(self):
        raw = {
            **VALID_CONFIG,
            "remote_storage_options": {
                "aws_endpoint_url": "https://s3.example.org",
                "aws_region": "eu-west-1",
            },
            "user": {**VALID_CONFIG["user"], "_id": "507f1f77bcf86cd799439011"},
        }
        _, ignored = strip_unknown_cli_config_keys(raw)

        assert ignored == []


class TestValidateIgnoresUnknownKeys:
    def test_a_newer_server_configuration_loads_with_one_warning(self, printed_warnings):
        config = validate_depictio_cli_config(_config_from_a_newer_server())

        assert isinstance(config, CLIConfig)
        assert config.api_base_url == "https://api.depictio.dev"
        assert config.user.email == "test@example.com"
        printed_warnings.assert_called_once()
        message = printed_warnings.call_args[0][0]
        assert message == (
            "CLI.yaml has settings this CLI does not know "
            "(deployment_notes, s3_storage.future_s3_setting, telemetry_hint, "
            "user.sso_provider, user.token.mfa_bound): "
            "ignored. Your CLI may be older than the server."
        )

    def test_the_warning_is_printed_once_per_process(self, printed_warnings):
        validate_depictio_cli_config(_config_from_a_newer_server())
        validate_depictio_cli_config(_config_from_a_newer_server())

        printed_warnings.assert_called_once()

    def test_a_configuration_without_unknown_keys_prints_nothing(self, printed_warnings):
        validate_depictio_cli_config(VALID_CONFIG)

        printed_warnings.assert_not_called()

    def test_missing_required_field_still_fails(self):
        broken = _config_from_a_newer_server()
        del broken["user"]["token"]["access_token"]

        with pytest.raises(ValidationError) as excinfo:
            validate_depictio_cli_config(broken)

        assert "access_token" in str(excinfo.value)

    def test_missing_api_base_url_still_fails(self):
        broken = _config_from_a_newer_server()
        del broken["api_base_url"]

        with pytest.raises(ValidationError):
            validate_depictio_cli_config(broken)

    def test_missing_user_block_fails(self):
        broken = _config_from_a_newer_server()
        del broken["user"]

        with pytest.raises(KeyError):
            validate_depictio_cli_config(broken)


class TestMajorMinor:
    @pytest.mark.parametrize(
        ("version", "expected"),
        [
            ("1.22.2", (1, 22)),
            ("v1.22.2", (1, 22)),
            ("1.15.1-b3", (1, 15)),
            ("1.22", (1, 22)),
        ],
    )
    def test_releases_parse(self, version, expected):
        assert major_minor(version) == expected

    @pytest.mark.parametrize("version", ["dev", "", "not-a-version", "2025-06-30", None])
    def test_unparsable_versions_return_none(self, version):
        assert major_minor(version) is None


class TestVersionMismatchWarning:
    def test_same_minor_is_silent(self):
        assert version_mismatch_warning("1.22.0", "1.22.2") is None
        assert version_mismatch_warning("1.22.2", "1.22.0") is None

    def test_an_older_cli_warns_and_names_the_fix(self):
        warning = version_mismatch_warning("1.21.0", "1.22.2")

        assert warning is not None
        assert "1.21.0" in warning
        assert "1.22.2" in warning
        assert 'uv tool install "depictio==1.22.*"' in warning

    def test_a_newer_cli_warns_too(self):
        warning = version_mismatch_warning("1.23.0", "1.22.2")

        assert warning is not None
        assert 'uv tool install "depictio==1.22.*"' in warning

    def test_a_different_major_warns(self):
        assert version_mismatch_warning("2.0.0", "1.22.2") is not None

    def test_a_dev_cli_is_silent(self):
        assert version_mismatch_warning("dev", "1.22.2") is None

    def test_an_unparsable_server_version_is_silent(self):
        assert version_mismatch_warning("1.21.0", "not-a-version") is None


def _client(status_code=200, version="1.22.2", error=None):
    """An httpx.Client stand-in answering the /utils/status endpoint."""
    client = MagicMock()
    if error is not None:
        client.get.side_effect = error
        return client
    response = MagicMock(status_code=status_code)
    response.json.return_value = {"status": "online", "version": version}
    client.get.return_value = response
    return client


class TestFetchServerVersion:
    def test_the_version_endpoint_is_read(self):
        client = _client(version="1.22.2")

        assert fetch_server_version("http://localhost:8058", client=client) == "1.22.2"
        client.get.assert_called_once_with(
            "http://localhost:8058/depictio/api/v1/utils/status", timeout=5.0
        )

    def test_a_non_200_answer_gives_no_version(self):
        assert (
            fetch_server_version("http://localhost:8058", client=_client(status_code=404)) is None
        )

    def test_an_unreachable_endpoint_gives_no_version(self):
        import httpx

        client = _client(error=httpx.ConnectError("Connection refused"))

        assert fetch_server_version("http://localhost:9999", client=client) is None


class TestCheckServerVersion:
    def test_a_minor_difference_warns(self, printed_warnings):
        with patch("depictio.cli.cli.utils.config_compat.cli_version", return_value="1.21.0"):
            check_server_version("http://localhost:8058", client=_client(version="1.22.2"))

        printed_warnings.assert_called_once()
        assert 'uv tool install "depictio==1.22.*"' in printed_warnings.call_args[0][0]

    def test_the_same_minor_stays_silent(self, printed_warnings):
        with patch("depictio.cli.cli.utils.config_compat.cli_version", return_value="1.22.0"):
            check_server_version("http://localhost:8058", client=_client(version="1.22.2"))

        printed_warnings.assert_not_called()

    def test_a_dev_cli_stays_silent(self, printed_warnings):
        with patch("depictio.cli.cli.utils.config_compat.cli_version", return_value="dev"):
            check_server_version("http://localhost:8058", client=_client(version="1.22.2"))

        printed_warnings.assert_not_called()

    def test_an_unreachable_endpoint_never_blocks(self, printed_warnings):
        import httpx

        client = _client(error=httpx.ConnectError("Connection refused"))

        with patch("depictio.cli.cli.utils.config_compat.cli_version", return_value="1.21.0"):
            check_server_version("http://localhost:9999", client=client)

        printed_warnings.assert_not_called()


class TestCheckServerVersionOfConfig:
    def test_the_server_the_configuration_names_is_checked(self, tmp_path, printed_warnings):
        import yaml

        config = tmp_path / "CLI.yaml"
        config.write_text(yaml.safe_dump(VALID_CONFIG))
        with (
            patch("depictio.cli.cli.utils.config_compat.cli_version", return_value="1.21.0"),
            patch(
                "depictio.cli.cli.utils.config_compat.fetch_server_version",
                return_value="1.22.2",
            ) as fetch,
        ):
            check_server_version_of_config(str(config))

        fetch.assert_called_once_with("https://api.depictio.dev", client=None, timeout=5.0)
        printed_warnings.assert_called_once()

    def test_a_missing_configuration_never_blocks(self, tmp_path, printed_warnings):
        check_server_version_of_config(str(tmp_path / "absent-CLI.yaml"))

        printed_warnings.assert_not_called()

    def test_warn_about_unknown_keys_is_the_single_message(self, printed_warnings):
        warn_about_unknown_keys(["s3_storage.browser_access"])

        printed_warnings.assert_called_once()
        assert printed_warnings.call_args[0][0] == (
            "CLI.yaml has settings this CLI does not know (s3_storage.browser_access): "
            "ignored. Your CLI may be older than the server."
        )
