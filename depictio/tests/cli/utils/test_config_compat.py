"""CLI.yaml compatibility: unknown keys from a newer server, and the version check.

A CLI.yaml is generated by the server it was downloaded from, which may be newer
than the CLI reading it. The loader drops the keys this CLI does not know (one
warning naming them) and a different minor version warns, but never blocks.
"""

