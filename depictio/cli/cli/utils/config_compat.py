"""Compatibility between a CLI and a server of a different version.

Two guards live here, both about the same situation: a ``CLI.yaml`` is
generated by the server it was downloaded from, and the CLI reading it may be
older (or newer) than that server.

- :func:`strip_unknown_cli_config_keys` drops the keys this CLI's models do
  not know, so an older CLI can still load a newer server's configuration,
  and :func:`warn_about_unknown_keys` says which ones were dropped, once.
- :func:`check_server_version` compares the CLI's version with the server's
  and warns when they are on different major.minor lines. It never blocks:
  an unreachable endpoint, a dev checkout or an unparsable version is at
  most a debug log.
"""

import re
from typing import Any, Union, get_args, get_origin

from pydantic import AliasChoices, BaseModel
from pydantic.fields import FieldInfo

from depictio.cli.cli.utils.rich_utils import rich_print_checked_statement
from depictio.cli.cli.utils.telemetry import cli_version
from depictio.cli.cli_logging import logger
from depictio.models.models.cli import CLIConfig

# ── Unknown keys in CLI.yaml ──────────────────────────────────────────────────

# Legacy spellings validate_depictio_cli_config still accepts at the top level.
_ROOT_ALIASES: dict[str, str] = {"base_url": "api_base_url", "s3": "s3_storage"}


def _field_for_key(model_cls: type[BaseModel], key: str) -> FieldInfo | None:
    """The field a key of ``model_cls`` feeds, under any spelling it accepts.

    Covers field names, aliases and ``AliasChoices``, so a key the model
    accepts under another name (``aws_endpoint_url``, ``_id``) is not mistaken
    for one a newer server invented.
    """
    if key in _ROOT_ALIASES and model_cls is CLIConfig:
        key = _ROOT_ALIASES[key]
    fields = model_cls.model_fields
    if key in fields:
        return fields[key]
    for field in fields.values():
        names: set[str] = set()
        if field.alias:
            names.add(field.alias)
        validation_alias = field.validation_alias
        if isinstance(validation_alias, str):
            names.add(validation_alias)
        elif isinstance(validation_alias, AliasChoices):
            names.update(choice for choice in validation_alias.choices if isinstance(choice, str))
        if key in names:
            return field
    # MongoModel.ensure_id moves _id onto id before validation, so both load.
    if key == "_id" and "id" in fields:
        return fields["id"]
    return None


def _nested_models(annotation: Any) -> list[type[BaseModel]]:
    """The model classes a value of this annotation may be validated into."""
    origin = get_origin(annotation)
    if origin is Union:
        models: list[type[BaseModel]] = []
        for arg in get_args(annotation):
            models.extend(_nested_models(arg))
        return models
    if origin in (list, tuple, set, frozenset):
        args = get_args(annotation)
        return _nested_models(args[0]) if args else []
    if isinstance(annotation, type) and issubclass(annotation, BaseModel):
        return [annotation]
    return []


def _strip_unknown(model_cls: type[BaseModel], data: Any, prefix: str, ignored: list[str]) -> Any:
    """``data`` without the keys ``model_cls`` does not know, recursively.

    Non-dict values pass through untouched, and so does a dict under an
    annotation with several model candidates: neither can reach a
    ``extra="forbid"`` check with a key this walk left in. ``ignored`` collects
    the dropped keys as dotted paths.
    """
    if not isinstance(data, dict):
        return data
    cleaned: dict[str, Any] = {}
    for key, value in data.items():
        field = _field_for_key(model_cls, key)
        if field is None:
            ignored.append(f"{prefix}{key}")
            continue
        models = _nested_models(field.annotation)
        if isinstance(value, dict) and len(models) == 1:
            cleaned[key] = _strip_unknown(models[0], value, f"{prefix}{key}.", ignored)
        elif isinstance(value, list) and models:
            cleaned[key] = [
                _strip_unknown(models[0], item, f"{prefix}{key}[{index}].", ignored)
                if isinstance(item, dict)
                else item
                for index, item in enumerate(value)
            ]
        else:
            cleaned[key] = value
    return cleaned


def strip_unknown_cli_config_keys(raw: dict) -> tuple[dict, list[str]]:
    """``raw`` purged of the keys this CLI's configuration models do not know.

    Returns the cleaned dict and the dropped keys as sorted dotted paths
    (``s3_storage.browser_access``), ready for the warning. Keys the
    configuration models themselves ignore (:class:`CLIConfig` and friends are
    ``extra="ignore"``) are kept out of the models' way here too, so the
    warning is the single place unknown keys are reported.
    """
    ignored: list[str] = []
    cleaned = _strip_unknown(CLIConfig, raw, "", ignored)
    return cleaned, sorted(ignored)


# Warnings already printed in this process: a command loads its configuration
# several times (login, then each step), and once is enough.
_warned: set[str] = set()


def warn_about_unknown_keys(ignored: list[str]) -> None:
    """Say, once, which configuration keys were dropped as unknown.

    The usual cause is a ``CLI.yaml`` written by a server newer than this CLI:
    the keys list names exactly what this CLI did not understand.
    """
    if not ignored:
        return
    message = (
        f"CLI.yaml has settings this CLI does not know ({', '.join(ignored)}): "
        "ignored. Your CLI may be older than the server."
    )
    if message in _warned:
        return
    _warned.add(message)
    # rich already says it in the terminal; the log only traces it.
    logger.debug(message)
    rich_print_checked_statement(message, "warning")


# ── Server version check ─────────────────────────────────────────────────────

# Plain releases ("1.22.2"), pre-releases ("1.15.1-b3") and short forms
# ("1.22"); anything else ("dev", a commit hash) does not parse.
_VERSION = re.compile(r"^\s*v?(\d+)\.(\d+)(?:\.\d+)?(?:[-+].*)?$")


def major_minor(version: str) -> tuple[int, int] | None:
    """The (major, minor) of a version string, or None when it does not parse."""
    match = _VERSION.match(str(version))
    return (int(match.group(1)), int(match.group(2))) if match else None


def version_mismatch_warning(cli: str, server: str) -> str | None:
    """The warning for a CLI and a server on different major.minor lines, if any.

    Silent (None) when both are on the same line, and when either version does
    not parse — a dev checkout or an exotic build must not nag.
    """
    cli_line = major_minor(cli)
    server_line = major_minor(server)
    if cli_line is None or server_line is None or cli_line == server_line:
        return None
    return (
        f"Depictio CLI {cli} talking to a {server} server: align versions with "
        f'uv tool install "depictio=={server_line[0]}.{server_line[1]}.*"'
    )


def fetch_server_version(api_base_url: str, client: Any = None, timeout: float = 5.0) -> str | None:
    """The server's version from its public /utils/status endpoint, or None.

    None also for an unreachable endpoint, a non-200 answer or a body without
    a version: the check must never be the reason a command fails.
    """
    from depictio.cli.cli.utils.common import get_http_client

    try:
        http = client if client is not None else get_http_client()
        response = http.get(
            f"{str(api_base_url).rstrip('/')}/depictio/api/v1/utils/status", timeout=timeout
        )
        if response.status_code != 200:
            logger.debug(f"Version endpoint answered HTTP {response.status_code}")
            return None
        version = response.json().get("version")
        return str(version) if version else None
    except Exception as exc:  # noqa: BLE001 - never block on the version probe
        logger.debug(f"Could not read the server version: {exc}")
        return None


def check_server_version(api_base_url: str, client: Any = None, timeout: float = 5.0) -> None:
    """Warn when this CLI and the server are on different major.minor lines.

    Never raises and never blocks: any failure on the way is a debug log, and
    the warning itself is printed once per process.
    """
    try:
        server = fetch_server_version(api_base_url, client=client, timeout=timeout)
        warning = version_mismatch_warning(cli_version(), server or "")
    except Exception as exc:  # noqa: BLE001 - the check must never break a command
        logger.debug(f"Server version check skipped: {exc}")
        return
    if not warning or warning in _warned:
        return
    _warned.add(warning)
    # rich already says it in the terminal; the log only traces it.
    logger.debug(warning)
    rich_print_checked_statement(warning, "warning")


def check_server_version_of_config(yaml_config_path: str) -> None:
    """:func:`check_server_version` for the server a CLI configuration points at.

    Reads the configuration quietly; one it cannot read is a debug log, not an
    error — whatever load the configuration was named for has already said so.
    """
    from depictio.cli.cli.utils.common import read_depictio_config

    try:
        cli_config = read_depictio_config(yaml_config_path)
    except Exception as exc:  # noqa: BLE001 - never block on the version probe
        logger.debug(f"Server version check skipped: {exc}")
        return
    check_server_version(str(cli_config.api_base_url))
