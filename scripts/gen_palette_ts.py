#!/usr/bin/env python3
"""Write the TypeScript copy of depictio's palettes from the JSON source of truth.

    python scripts/gen_palette_ts.py           # (re)write the generated file
    python scripts/gen_palette_ts.py --check   # exit 1 when it is stale

Source: depictio/models/palettes/depictio_palettes.json
Output: packages/depictio-react-core/src/palettes.generated.ts
"""

from __future__ import annotations

import argparse
import importlib.util
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "depictio" / "models" / "palettes" / "depictio_palettes.json"
TARGET = ROOT / "packages" / "depictio-react-core" / "src" / "palettes.generated.ts"

UI_HUES_MODULE = ROOT / "depictio" / "models" / "palettes" / "ui_hues.py"


def _load_ui_hues():
    """``ui_hues.py`` by path: it is pure stdlib, and importing ``depictio`` is not needed here."""
    spec = importlib.util.spec_from_file_location("depictio_palettes_ui_hues", UI_HUES_MODULE)
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


HEADER = """\
// GENERATED by scripts/gen_palette_ts.py from
// depictio/models/palettes/depictio_palettes.json. Do not edit by hand:
// edit the JSON, then run `python scripts/gen_palette_ts.py`.
"""


def dump_ui_tuples(tuples: dict) -> str:
    """The remap tuples with one line per scheme: 1,400 hexes stay readable and short."""
    lines = ["{"]
    for pid, hues in tuples.items():
        lines.append(f"  {json.dumps(pid)}: {{")
        for hue, modes in hues.items():
            light, dark = json.dumps(modes["light"]), json.dumps(modes["dark"])
            lines.append(f"    {json.dumps(hue)}: {{ light: {light}, dark: {dark} }},")
        lines.append("  },")
    lines.append("}")
    return "\n".join(lines)


def render(data: dict) -> str:
    def dump(value) -> str:
        return json.dumps(value, indent=2, ensure_ascii=False)

    palettes = {
        pid: {
            k: spec[k] for k in ("label", "description", "categorical", "sequential", "diverging")
        }
        for pid, spec in data["palettes"].items()
    }
    ids = list(palettes)
    ui_hues = _load_ui_hues()
    ui_names = list(data["ui_hues"]["default"])
    ui_tuples = {pid: ui_hues.ui_hue_tuples(data, pid) for pid in ids}
    shade_dl = data["style"]["overflow_shade_dl"]
    overflow_shades = {
        pid: {
            m: ui_hues.overflow_shades(data["palettes"][pid]["categorical"][m], shade_dl[m])
            for m in ("light", "dark")
        }
        for pid in ids
    }
    return (
        HEADER
        + "\n"
        + f"export const PALETTE_IDS = {dump(ids)} as const;\n\n"
        + "export type PaletteId = (typeof PALETTE_IDS)[number];\n\n"
        + "export interface PaletteModes {\n  light: readonly string[];\n  dark: readonly string[];\n}\n\n"
        + "export interface PaletteSpec {\n  label: string;\n  description: string;\n"
        + "  categorical: PaletteModes;\n  sequential: PaletteModes;\n  diverging: PaletteModes;\n}\n\n"
        + f"export const DEFAULT_PALETTE_ID: PaletteId = {json.dumps(data['default'])};\n\n"
        + f"export const PALETTE_SLOTS = {data['slots']};\n\n"
        + f"export const PALETTES: Record<PaletteId, PaletteSpec> = {dump(palettes)};\n\n"
        + "export type ReservedKind = 'other' | 'unclassified' | 'na';\n\n"
        + f"export const SEMANTIC_COLORS: Record<ReservedKind, PaletteModesSingle> = {dump(data['semantic'])};\n\n"
        + f"export const RESERVED_VALUES: Record<ReservedKind, readonly string[]> = {dump(data['reserved_values'])};\n\n"
        + f"export const ANNOTATION_INK: PaletteModesSingle = {dump(data['annotation_ink'])};\n\n"
        + f"export const PLOT_FONT_FAMILY = {json.dumps(data['chrome']['font_family'])};\n\n"
        + "export interface ChromeTokens {\n"
        + "".join(f"  {k}: string;\n" for k in data["chrome"]["light"])
        + "}\n\n"
        + "export const PLOT_CHROME: Record<'light' | 'dark', ChromeTokens> = "
        + dump({m: data["chrome"][m] for m in ("light", "dark")})
        + ";\n\n"
        + f"export const BAR_CORNER_RADIUS = {data['style']['bar_corner_radius']};\n\n"
        + f"export const OVERVIEW_TOP_N = {data['style']['top_n']};\n\n"
        + "/** What a value past the last slot gets: the Other grey, or first a shade twin. */\n"
        + f"export const OVERFLOW_MODE: 'other' | 'shade' = {json.dumps(data['style']['overflow'])};\n\n"
        + "/** Each palette's slots shifted in lightness, for `OVERFLOW_MODE = 'shade'`. */\n"
        + f"export const OVERFLOW_SHADES: Record<PaletteId, PaletteModes> = {dump(overflow_shades)};\n\n"
        + "export interface ScatterMarkerBucket {\n  max_n: number | null;\n  size: number;\n"
        + "  opacity: number;\n  outline: boolean;\n}\n\n"
        + f"export const SCATTER_MARKERS: readonly ScatterMarkerBucket[] = {dump(data['style']['scatter_markers'])};\n\n"
        + "/** A reference line and its label: width, dash, label size, and the `PLOT_CHROME`\n"
        + " *  tokens their colours come from. */\n"
        + "export interface ReferenceGuideStyle {\n  width: number;\n  dash: 'dash' | 'dot' | 'solid';\n"
        + "  font_size: number;\n  line: keyof ChromeTokens;\n  label: keyof ChromeTokens;\n}\n\n"
        + f"export const REFERENCE_GUIDE: ReferenceGuideStyle = {dump(data['style']['reference_guide'])};\n\n"
        + "/** Line strokes: `width` up to `many_series` lines, `width_many` past it; a\n"
        + " *  series of at most `marker_max_points` points shows a dot on each. */\n"
        + "export interface LineStyle {\n  width: number;\n  width_many: number;\n"
        + "  many_series: number;\n  marker_max_points: number;\n}\n\n"
        + f"export const LINE_STYLE: LineStyle = {dump(data['style']['line_style'])};\n\n"
        + "export const UI_HUES = "
        + dump(ui_names)
        + " as const;\n\n"
        + "export type UiHue = (typeof UI_HUES)[number];\n\n"
        + "/** A dashboard's Mantine hue names re-drawn in a palette: 10 shades per scheme\n"
        + " *  (light: slot colour on 6; dark: dark slot colour on 4). */\n"
        + "export interface UiHueTuple {\n  light: string[];\n  dark: string[];\n}\n\n"
        + f"export const UI_HUE_TUPLES: Record<PaletteId, Record<UiHue, UiHueTuple>> = {dump_ui_tuples(ui_tuples)};\n\n"
        + "export interface PaletteModesSingle {\n  light: string;\n  dark: string;\n}\n"
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check", action="store_true", help="fail when the generated file is stale"
    )
    args = parser.parse_args()
    expected = render(json.loads(SOURCE.read_text("utf-8")))
    if args.check:
        if not TARGET.exists() or TARGET.read_text("utf-8") != expected:
            print(
                f"{TARGET.relative_to(ROOT)} is stale: run python scripts/gen_palette_ts.py",
                file=sys.stderr,
            )
            return 1
        return 0
    TARGET.write_text(expected, "utf-8")
    print(f"wrote {TARGET.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
