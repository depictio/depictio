#!/usr/bin/env python
"""Generate the browser's advanced-viz sampling table from the server's.

Writes ``src/generated/sampling.ts`` (``KIND_SAMPLING_POLICY`` + ``TAIL_ROLE``,
read verbatim off ``depictio/models/components/advanced_viz/sampling.py``) and
``fixtures/sampling-expected.json`` (``log_spaced_rank_thin`` ground truth for
the vitest port).

The TS table used to be a hand copy and drifted: it listed 18 of the 54 kinds,
so every kind added since fell back to ``hash`` and a ``none`` kind such as
``stacked_bar`` was silently hash-sampled in the bundle while the server served
it whole. Both outputs are committed and
``depictio/tests/unit/serverless/test_sampling_table.py`` fails when either
differs from what this script would write now.

Run with the repo venv:

    uv run --extra dev python packages/depictio-static-core/scripts/generate_sampling_table.py
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import get_args

from depictio.models.components.advanced_viz.sampling import (
    KIND_SAMPLING_POLICY,
    TAIL_ROLE,
    log_spaced_rank_thin,
)
from depictio.models.components.types import AdvancedVizKind

HERE = Path(__file__).resolve().parent
TS_PATH = HERE.parent / "src" / "generated" / "sampling.ts"
FIXTURE_PATH = HERE.parent / "fixtures" / "sampling-expected.json"

#: (n, cap) pairs the TS ``logSpacedRankThin`` must reproduce position for
#: position — small, degenerate and knee-plot-sized curves. Python's ``round``
#: is half-to-even, which is the one place a naive ``Math.round`` port drifts.
THIN_CASES: list[tuple[int, int]] = [
    (0, 10),
    (1, 10),
    (5, 10),
    (10, 10),
    (11, 10),
    (100, 1),
    (100, 2),
    (100, 3),
    (1000, 50),
    (12_345, 200),
    (100_000, 5000),
    (737_280, 2500),
]


def render_ts() -> str:
    kinds = list(get_args(AdvancedVizKind))
    missing = [k for k in kinds if k not in KIND_SAMPLING_POLICY]
    if missing:
        raise SystemExit(f"sampling.py has no policy for {missing}")
    lines = [
        "// GENERATED by packages/depictio-static-core/scripts/generate_sampling_table.py",
        "// from depictio/models/components/advanced_viz/sampling.py. Do not edit by",
        "// hand: depictio/tests/unit/serverless/test_sampling_table.py fails on drift.",
        "",
        "export type SamplingPolicy = 'hash' | 'none' | 'tail' | 'log_rank' | 'head';",
        "export type DeclaredTailDirection = 'low' | 'high' | 'both' | 'auto' | 'top';",
        "",
        "/** Every `AdvancedVizKind`, in declaration order (types.py). */",
        "export const ADVANCED_VIZ_KINDS: readonly string[] = [",
    ]
    lines += [f"  '{k}'," for k in kinds]
    lines += [
        "];",
        "",
        "/** sampling.py::KIND_SAMPLING_POLICY. */",
        "export const KIND_SAMPLING_POLICY: Readonly<Record<string, SamplingPolicy>> = {",
    ]
    lines += [f"  {k}: '{KIND_SAMPLING_POLICY[k]}'," for k in kinds]
    lines += [
        "};",
        "",
        "/** sampling.py::TAIL_ROLE — (role, declared direction). */",
        "export const TAIL_ROLE: Readonly<",
        "  Record<string, readonly [role: string, direction: DeclaredTailDirection]>",
        "> = {",
    ]
    for kind, (role, direction) in TAIL_ROLE.items():
        lines.append(f"  {kind}: ['{role}', '{direction}'],")
    lines += ["};", ""]
    return "\n".join(lines)


def render_fixture() -> str:
    cases = [
        {"n": n, "cap": cap, "positions": log_spaced_rank_thin(n, cap)} for n, cap in THIN_CASES
    ]
    return json.dumps({"log_spaced_rank_thin": cases}, separators=(",", ":")) + "\n"


def main() -> None:
    TS_PATH.parent.mkdir(parents=True, exist_ok=True)
    TS_PATH.write_text(render_ts())
    FIXTURE_PATH.write_text(render_fixture())
    print(f"wrote {TS_PATH}\nwrote {FIXTURE_PATH}")


if __name__ == "__main__":
    main()
